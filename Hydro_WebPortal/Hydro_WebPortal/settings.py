# Load environment variables from .env files
def load_env_files():
    """Load environment variables from .env, .env.production, .env.era5, and workspace-root .env files.
    Local .env files take priority; .env.production is loaded last (lowest priority).
    DEBUG always defaults to True so .env.production's DEBUG=False never affects local dev.
    Platform-specific library paths are protected on Windows before .env.production is read.
    """
    import platform
    django_root = Path(__file__).resolve().parent.parent
    workspace_root = django_root.parent

    # Protect settings that must not be overridden on Windows by Linux-specific .env.production values
    os.environ.setdefault('DEBUG', 'True')
    if platform.system() == 'Windows':
        _gdal = str(django_root.parent / 'myenv' / 'Lib' / 'site-packages' / 'osgeo' / 'gdal.dll')
        _geos = str(django_root.parent / 'myenv' / 'Lib' / 'site-packages' / 'osgeo' / 'geos_c.dll')
        os.environ.setdefault('GDAL_LIBRARY_PATH', _gdal)
        os.environ.setdefault('GEOS_LIBRARY_PATH', _geos)

    candidates = [
        workspace_root / '.env',             # local overrides (highest priority)
        django_root / '.env',
        django_root / '.env.era5',
        workspace_root / '.env.production',  # base/shared secrets (lowest priority)
    ]
    for env_file in candidates:
        if env_file.exists():
            with open(env_file, 'r') as f:
                for line in f:
                    line = line.strip()
                    if line and not line.startswith('#') and '=' in line:
                        key, value = line.split('=', 1)
                        os.environ.setdefault(key.strip(), value.strip())

